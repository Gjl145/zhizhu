 *    「保持现在的按键不变。其他的，包括之后我不明白说明的情况下
 *      不准再新增加按键。」
 *
 *  这条约束的意思：
 *    · 即使某个功能「需要」一个新键，也要先问用户，不能自己决定
 *    · 优先考虑：能否用现有键的组合来实现？
 *    · 「我觉得这样更好用」不构成新增按键的理由
 *
 *  ── 最终键位（8 个，勿改）──
 *      WASD / QE    移动 / 升降
