    /* ========================================================================
     *  ★★ 关于「蛛丝到底用来干什么」的查证结论
     * ========================================================================
     *
     *  用户提问：「蜘蛛侠的钩爪或蛛丝的主要作用是不是把自己拉到锚点，
     *            而不是提供摆荡？」
     *
     *  【答案：两者都有，但在游戏里是分开的两个键】
     *
     *  查证来源：Marvel's Spider-Man 2 官方操作表（Fandom Wiki）
     *
     *      Swing          按住 R2   摆荡（周期性往返）
     *      Web Zip        空中 X    荡着时向前冲刺
     *      Zip To Point   按 R1     ★拉拽到瞄准点（直线快速接近）
     *      Point Launch   落地前 +  借拉拽的惯性弹射出去
     *
     *  官方对 Zip To Point 的描述：
     *      「Fire out webs to **zip to a highlighted point**」
     *      中文攻略：「按 R1 向瞄准点**快速拉近**」
     *  中文攻略补充：「瞄准建筑物上的**白圈**，按 R2 直接发射到该点」
     *
     *  → 所以「拉拽」是**独立能力**，不是摆荡的副产品。
     *  → 而它正是我们**完全缺失**的那一个。
     *
     *  --------------------------------------------------------------------
     *  ★ 为什么「拉拽」对我们比「继续优化摆荡」收益更大
     *  --------------------------------------------------------------------
     *
     *  1. **摆荡的固有局限 —— 它是钟摆，不是位移工具**
     *      周期 T = 2π√(L/g) 与速度无关，14 格绳长就是 3.32 秒。
     *      玩家想做「快速到某处」时，摆荡帮不上忙 ——
     *      它本质是**周期性往返**，不是定向移动。
     *      所以「摆荡太慢」可能不是 bug，而是**能力单一**的必然结果。
     *
     *  2. **垂直移动能力严重缺失**
     *      当前跳跃 apex 只有 6.76 格、跨度 26 格。
     *      想上 20 格高的平台？跳不上去，荡也荡不上去 —— 只能看着。
     *      这迫使所有关卡设计「把目标放低」，因为够不到。
     *      拉拽正是解决这个的：直接把你拽上去。
     *
     *  → 补上拉拽能一次性解决「移动能力单调」与「垂直够不到」两个问题，
     *    而摆荡手感的好坏影响就没那么致命了。
     *
     *  --------------------------------------------------------------------
     *  ★ 消逝之光2 的对照
     *  --------------------------------------------------------------------
     *  官方操作：「在跳跃过程中按 L2/LT 释放抓钩，将其作为绳索摆动」
     *  社区攻略的用法同时覆盖两种：
     *      · 「抓钩抓住吊灯荡到对面」      ← 摆荡
     *      · 「连续利用钩爪前往指定位置，这里需要**二连抓**」← 连续位移
     *  → 同样两用，但**摆荡是主线**，位移是附加收益。
     * ========================================================================

