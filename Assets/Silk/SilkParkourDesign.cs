/* ============================================================================
 *  跑酷机制设计参照 —— 三款标杆游戏的对比与我们的取舍
 * ============================================================================
 *
 *  【为什么有这份文档】
 *  用户提供了三个参考作品。它们不是同一种游戏，但**在「移动手感」上
 *  共享同一套设计哲学**。把差异与共性梳理清楚，
 *  避免每做一个功能都凭感觉调参数。
 *
 * ============================================================================
 *  一、三款参考的核心差异
 * ============================================================================
 *
 *  【蜘蛛侠2 —— 摆荡类】
 *    核心：momentum carries between swings（动量在摆荡之间保留）
 *    · 地面跑动只是补充手段。官方原话：
 *      「密集区域地面跑动比反复短摆荡更快」
 *    · 松手时机决定收益：最低点松手 = 换速度；最高点松手 = 换高度
 *    · 加速来源是【摆荡】，不是【跑动】
 *    对我们的意义：动量守恒是最底层的一条，已经实现。
 *
 *  【幽灵行者 Ghostrunner —— 冲刺类（第一人称）】
 *    核心：MOMENTUM FIRST（动量优先），连死亡都要快
 *    · 跑墙 → 跳 → 跑另一面墙，**无缝衔接、不落地**
 *      Polygon：「leaping from one wall to the next feel more like
 *      flying than the traditional locomotion」
 *    · 技能不是独立功能，而是**动量累积器**：
 *      冲刺（Dash，空中按住=时间减速，松手=从新位置冲出）
 *      滑铲（Slide）→ 跳 → 再滑铲，快速积累动量
 *      跑墙（Wall-run）→ 起跳时带着动量 -> 直接进入下一面墙
 *    · 死亡瞬间重生、失败不惩罚 -> 鼓励不断尝试
 *    对我们的意义：**最值得抄**。它把跑墙/滑铲/冲刺做成
 *      一个「动量链」，而不是三个孤立的技能。
 *
 *  【消逝的光芒 2 —— 跑酷类（第一人称）】
 *    核心：momentum preservation（动量保存）
 *    · 对比一代的失败：「撞到障碍速度就全没了」
 *      二代的做法是**给玩家多个「出路」**保持速度（跑墙、主动落地）
 *    · **跳跃高度随动量缩放** —— 跑得越快跳得越高
 *      （奖励技巧，而不是单纯的数值）
 *    · 滑铲 → 翻越 → 跑墙连成flow state（节奏流）
 *    · 钩爪从一代的「传送」改成「真实的绳子」，
 *      **融入跑酷循环而非绕过它** —— 这点极重要
 *    对我们的意义：跳跃高度与速度挂钩，能让「跑得快」有实际收益。
 *
 * ============================================================================
 *  二、三者的共同点（这才是重点）
 * ============================================================================
 *
 *  1. **动量是核心资产** —— 任何操作都不该无故清零速度。
 *     我们踩过这个坑（`flatVel = Vector3.zero`）。
 *
 *  2. **技能是「动量累积器」而非独立功能**。
 *     跑墙/滑铲/冲刺互相衔接、叠加，而不是各管一段。
 *
 *  3. **动作之间无缝衔接** —— 不落地、不中断、不进入「恢复状态」。
 *     这是我们目前最大的差距：现在跳完就落地、速度归零。
 *
 *  4. **失败要快、重生要快** —— 鼓励不断尝试而非谨慎行事。
 *
 * ============================================================================
 *  三、我们的现状与缺口
 * ============================================================================
 *
 *  已有：
 *    · 摆荡（SilkChain 约束链）
 *    · 动量守恒（AdoptFlightMomentum + momentumBleed）
 *    · 自动瞄准（PickBestAnchor）
 *    · 跳跃（抛物线，与水平速度分开积分）
 *    · **冲刺 Dash**（DoDash：瞬时冲量 + 冷却 + 空中限一次）
 *
 *  【项目方向：主要模拟蜘蛛侠】
 *  用户明确取舍：**不做滑铲、不做跑墙**，专注摆荡路线的深度。
 *  滑铲/跑墙都是《幽灵行者》的招牌，属于第一人称冲刺类玩法 ——
 *  与我们的蜘蛛侠式摆荡是两条不同的路，抄进来反而会打架。
 *
 *  缺口（按性价比排序）：
 *    1. **跳跃高度随速度缩放**（消逝之光2 的做法）——
 *       `jumpSpeed *= 1 + speedRatio * k`。
 *       跑得越快跳得越高，让「保持速度」有实际收益。
 *    2. **动作间无缝衔接** —— 现在跳完就落地、速度归零。
 *       摆荡->松手->冲刺->再摆荡的循环要能连起来。
 *
 *  【冲刺的设计取舍】
 *  · 借幽灵行者的「空中每次滞空限一次」规则 —— 让冲刺成为**决策**
 *    而不是无脑连按（有速度上限才有节奏感）。
 *  · 不做幽灵行者的「按住 Dash = 时间减速」—— 那是第一人称视角的设计，
 *    摆荡游戏的核心是速度而非时间操控。
 *  · 消逝之光2 把钩爪从「传送」改成「真实的绳子」；同理冲刺**只是加速**
 *    而非瞬移，位置仍靠速度积分推进，保持物理连续性。
 *
 *  【为什么先做冲刺】摆荡的节奏完全取决于「松手那一瞬的速度」。
 *  没有冲刺，玩家只能用「一直按住方向键」这种笨办法调速度；
 *  有了冲刺就有了「主动控制节奏」的手段 —— 这是蜘蛛侠摆荡手感的关键。
 * ============================================================================
 *
 * ============================================================================
 *  四、参数换算参考
 * ============================================================================
 *
 *  跳跃最高点 apex = v²/(2g)，滞空 airtime = 2v/g
 *  水平跨度 reach = speed × airtime
 *
 *  当前：g=50、jumpSpeed=26 -> apex 6.8 格、airtime 1.04 秒
 *       moveSpeed=50 -> 全速起跳跨度 52 格
 *       dashImpulse=42 -> 冲刺后 92 格/秒（1.8 倍）
 *       dashLift=14 -> 空中额外拉高 1.96 格
 *
 *  台阶落差 4 格 -> apex 需 ≥5 格才留得住余量（当前 6.8，余量 2.8）
 *
 * ============================================================================
 *  五、键位表（★ 已定稿，不得擅自新增）
 * ============================================================================
 *
 *  ═══════════════════════════════════════════════════════════════════
 *  ★★★硬约束：未经用户明确指示，禁止新增任何按键 ★★★
 * ═══════════════════════════════════════════════════════════════════
 *
