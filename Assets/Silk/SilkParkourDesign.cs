 *      鼠标左键      发射丝线（必须在空中）
 *      鼠标右键      松开丝线
 *      左 Shift      冲刺（按住则持续加速）
 *      C             固化当前位置为节点
 *      R             回起点
 *      Tab           切换 FreeFly / Parkour
 *      鼠标移动      改变视角（无需按键）
 *
 *  ── 已移除的键（方法体保留，但不要接回来）──
 *      B斜上发射（与左键重叠）
 *      V  结网
 *      X  断自发线  —— 断裂不是玩家控制的
 *      G  断视线线  —— 同上
 *      空格兼「空中抓线」—— 已简化，空中抓线由左键承担
 *
 *  ── FreeFly（编辑器世界）的键位独立，不受此约束 ──
 *
 * ============================================================================
 */

