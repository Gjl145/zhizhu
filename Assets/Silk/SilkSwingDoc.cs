using UnityEngine;   // Mathf.PI / Sqrt / Max —— 本文件只用到这三个

/* ============================================================================
 *  摆荡手感诊断与调参手册
 * ============================================================================
 *
 *  【为什么有这份文档】
 *  用户反馈「丝线断裂摆荡或没断裂的摆荡都太慢，应该没有实现
 *  和小球速度/动量相关的效果」。本文件记录：
 *   1. 用 Python 实算出的物理数字（不靠感觉调参）
 *   2. 与三款标杆游戏的架构差异
 *   3. 五个根因与对应修法
 *   4. 调参时的实算方法
 *
 * ============================================================================
 *  一、实算：我们的摆荡物理现状
 * ============================================================================
 *
 *  【约束模型】SilkChain 用「显式速度积分 + 距离约束迭代」：
 *     velocities[i] += gravity * dt
 *     velocities[i] *= dampCoef
 *     position[i] += velocities[i] * dt
 *     随后 solverIterations(8) 次迭代满足 |p[i]-p[i+1]| <= rest*(1+maxStrain)
 *
 *  【摆荡周期完全由绳长决定】单摆周期 T = 2π√(L/g)：
 *
 *      绳长 L      周期 T       荡到最低点
 *      20 格       3.97 秒      1.99 秒
 *      30 格       4.87 秒      2.44 秒
 *      45 格       5.96 秒      2.98 秒
 *
 *  → 对比：真实蜘蛛侠摆荡约 0.5~0.8 秒一个来回。
 *  → **这是「慢」的根本原因**：绳长 30 格时半周期就要 2.4 秒。
 *  → 调速的旋钮是**绳长**（不是泵力）：绳长缩短一半，周期缩短 √2 倍。
 *
 *  ============================================================================
 *  二、能量收支（决定能不能荡起来）
 *  ============================================================================
 *
 *  摆荡需要向心加速度 a = v²/L ≥ 约 0.3g 才能维持大幅摆动：
 *
 *      绳长   v=25      v=50      v=92
 *      20 格   31(够)    125(够)   423(够)
 *      30 格   21(勉强)  83(够)    282(够)
 *      45 格   14(死)    56(够)    188(够)
 *
 *  → 球速25 格/秒在长绳（45 格）上会「荡死」——
 *    这是设计约束：**绳长不得超过球速对应的极限**。
 *    进阶区平台的摆荡空间若超过 40 格，需要提高球速或缩短绳。
 *
 * ============================================================================
 *  三、与标杆的架构差异
 * ============================================================================
 *
 *  【我们：Verlet 约束链 + 隐式摆荡】
 *    · 球的位置 = 约束链末端（被动求解）
 *    · 摆荡周期 = 2π√(L/g) → 4~6 秒
 *    · 能量来源：**仅靠玩家按键注入的泵力**
 *    · 起摆瞬间速度 ≈ 0
 *    → 玩家感受：球挂在绳上小幅晃动，怎么按都慢
 *
 *  【标杆：摆荡是「能量管理」（共同点）】
 *    1. **动量在摆荡之间保留**（蜘蛛侠2 官方原话）
 *       发射瞬间继承玩家速度 → 摆荡从动能出发，不是从零
 *    2. **泵力是持续力**，能量源源不断，而非瞬时冲量
 *    3. **松手时末端速度全额转给玩家** → 「甩出去」的快感来源
 *       （消逝之光2 的钩爪是「真实的绳子」，不是传送）
 *    4. **绳长可变**：荡到最低点时绳长自动缩短、上升时变长（省力）
 *       这是蜘蛛侠荡得又高又远的原因
 *
 * ============================================================================
 *  四、五个根因与修法（2026-10-07 实施）
 * ============================================================================
 *
 *  【根因 1·已修】★ 飞行重力被硬编码成 15
 *      UpdateFlight 原写 `flightVel += (0,0,-15f) * dt`
 *      那是重力从 15 时代残留的常数，全局 gravity 改成 50 后没跟上
 *      → 松手后球的下落加速度只有正常的 **30%**，球像慢动作飘
 *      修法：改用 `gravity * flightGravityScale`（全局统一来源）
 *
 *  【根因 2·结构性】摆荡周期由绳长决定 = 4~6 秒
 *      这是物理公式决定的，不是 bug。调节手段见第五节。
 *
 *  【根因 3·已修】发射瞬间没有继承玩家速度
 *      旧行为：钩住后末端速度 ≈ 0，摆荡从静止开始
 *      修法：FireAtAnchor 里注入动量
 *            `chain.AddEndVelocity((flatVel + forward*vertVel) * swingEntryBoost)`
 *      swingEntryBoost：1.0 = 完全保留（推荐），
 *                       0.5 = 保留一半，0 = 回到旧行为
 *
 *  【根因 4·已修】阻尼双重衰减
 *      原代码 `vel *= damping(0.995); vel *= dragFactor(0.98)`
 *      每帧合计损失 2.5% → 半衰期仅 **0.33 秒**
 *      摆荡两三秒就没劲，全靠泵力硬撑
 *      修法：合并成单一指数衰减 `pow(damping, dt*60) * (1-airDrag)`
 *            airDrag 由 0.02 降到 0.005
 *      结果：半衰期 0.33 秒 → **1.16 秒**（改善 3.5 倍）
 *
 *  【根因 5·已修】泵力太弱
 *      原 pumpAccel=30，每帧注入 0.5 格/秒，被阻尼吃掉
 *      → 按住 4 秒才到 70 格/秒，反馈迟钝
 *      修法：提到 **90**（约 1.8g）
 *      结果：0.5 秒 -> 39 格/秒，2 秒 -> 105 格/秒
 *
 * ============================================================================
 *  五、调参手册（用实算，不要凭感觉）
 * ============================================================================
 *
 *  【想摆得更快】按效果排序：
 *    1. **缩短摆荡绳长** —— 最有效。周期 ∝ √L，绳长减半则快 √2 倍。
 *       检查 `slackScale`(1.15) 与 `catenarySag`(0.07)，它们都影响实际绳长。
 *    2. **提高球速** —— 向心加速度 ∝ v²。但会连带影响地面跑感。
 *    3. **提高 damping** —— 减少能量流失，但会让摆荡"停"得更快。
 *       0.995（半衰期 2.3 秒）已是推荐值，再高会显得不真实。
 *
 *  【想摆得更高】=摆得更远：
 *    · 松手时机决定收益（蜘蛛侠2 官方）：
 *      最低点松手 = 换速度，最高点松手 = 换高度
 *    · 我们已有 `GetEndVelocity()` 传给 flightVel（见 DoRelease）
 *
 *  【自检脚本可算的量】`.workbuddy/tools/selfcheck.py` 输出：
 *    跳跃最高点 apex = v²/(2g)
 *    滞空 airtime   = 2v/g
 *    全速起跳跨度 reach = moveSpeed × airtime
 *
 * ============================================================================
 *  六、下一步待验证（需要玩家实测）
 * ============================================================================
 *
 *  修完上述五项后，需要实测确认：
 *    1. 摆荡周期是否可接受？（太慢则缩短进阶区的绳长）
 *    2. swingEntryBoost 是否要调到 1.2~1.5？（更接近标杆的「一钩飞出去」）
 *    3. pumpAccel=90 是否过强？（可回调到 60）
 *    4. 进阶区的绳长是否超过球速极限？（见第二节的「荡死」分析）
 *
 * ============================================================================
 *  三点五、最低点绳长收缩（Reel-In）—— 2026-10-07 实现
 * ============================================================================
 *
 *  【为什么必须有这一步】
 *
 *  纯单摆在数学上**能量守恒**：
 *     荡到最高点，动能全部转成势能（v = 0）；
 *     再荡回来，势能全部转回动能（速度恢复原值）。
 *     **无论荡多少次，高度都不会超过第一次。**
 *
 *  那为什么蜘蛛侠能越荡越高？
 *  因为他在**最低点**（速度最大的瞬间）主动收绳——
 *  角动量守恒：L = m·v·r = 常数
 *       半径 r 减小  →  线速度 v 增大：v' = v × (r / r')
 *
 *      收缩 15% → 速度 ×1.18，周期缩短 8%
 *      收缩 20% → 速度 ×1.25，周期缩短 11%
 *
 *  【实现要点】
 *  1. **改restLengths，而不是直接拉末端位置。**
 *     直接改位置会凭空注入能量（位置突变→ 速度飙升 → 玩家被甩飞）。
 *     改自然长度由约束求解器温柔地拉回，**速度增益是物理的**。
 *
 *  2. **触发条件 = 垂直速度占比小**（|v.z| / |v| < 0.3）
 *     即「速度方向水平」—— 这才是最低点的物理特征。
 *     ★ 曾用「dist/totalLen > 0.92」判断，实算证明是错的：
 *       单摆全程绳长恒等于自然长度，该比值**永远是 1.0**，
 *       条件形同虚设，球在空中乱飞时也会误触发。
 *
 *  3. **每次摆荡只收缩一次**（`reeledThisSwing`）——
 *     否则连缩几次绳就变成线球，玩家完全失控。
 *
 *  【参数调整】
 *  · `reelInRatio` 0.15~0.2。太大则玩家被甩飞（0.4 是危险上限）。
 *    设 0 即完全关闭此机制。
 *  · `reelInMinSpeed` 15 格/秒 —— 低于此速度收缩没有意义。
 *  · `reelInMaxVerticalRatio` 0.3 —— 越小越精确，越大越频繁。
 *
 *  【还没做的下一步（标杆的完整版）】
 *  真实蜘蛛侠在荡到最低点时收绳、荡到最高点时**放绳**（变长），
 *  配合这个「呼吸」节奏才能持续攀高。本项目目前只做了收绳，
 *  放绳逻辑待观察收绳手感后再补。
 *
 * ============================================================================
 */

public static class SilkSwingDoc
{
    /// <summary>摆荡周期公式 —— 单摆，周期只由绳长与重力决定。
    /// 调速时优先调绳长（∝ √L），而不是泵力。</summary>
    public static float Period(float ropeLength, float gravity)
        => 2f * Mathf.PI * Mathf.Sqrt(ropeLength / Mathf.Max(gravity, 0.01f));

    /// <summary>维持摆动所需的最小向心加速度（格/秒²）。
    /// 经验阈值：低于重力的 30% 会「荡死」。</summary>
    public static float MinCentripetal(float speed, float ropeLength)
        => speed * speed / Mathf.Max(ropeLength, 0.01f);

    /// <summary>速度衰减的半衰期（秒）。
    /// 阻尼是「摆荡多久没劲」的决定因素。</summary>
    public static float HalfLife(float damping, float airDrag, float fps = 60f)
    {
        float loss = (1f - damping) + airDrag;
        if (loss <= 0.0001f) return float.PositiveInfinity;
        return 0.6931f / loss / fps;
    }
}